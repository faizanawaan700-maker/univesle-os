#!/usr/bin/env python3
"""Shared guard for scripts/*.py helpers that emit Phase 9 PowerShell scripts.

Both `write_backup.py` and `write_restore.py` previously opened their target
with mode "w", which silently overwrote the verified Phase 9 scripts with
early pre-fix drafts. That is how the 2,657-byte and 3,646-byte regressions
appeared on disk.

This module makes that impossible by default:

  * a target that already exists is NEVER overwritten unless the caller
    passes an explicit opt-in flag on the command line;
  * content is written to a temporary file in the same directory and then
    moved into place with os.replace(), so a partial write cannot clobber a
    good script;
  * the existing file's SHA256 is printed before any refusal so the operator
    can see exactly what is being protected.

Usage:
    python scripts/guard_helpers.py --selftest
"""
from __future__ import annotations

import hashlib
import os
import sys
import tempfile

# Scripts that must never be silently regenerated by a helper.
PROTECTED_TARGETS = (
    "pg-backup-phase9.ps1",
    "pg-restore-verify-phase9.ps1",
)


def sha256_of(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(65536), b""):
            h.update(chunk)
    return h.hexdigest().upper()


def safe_write(target: str, content: str, allow_overwrite: bool = False) -> int:
    """Write `content` to `target` without ever silently clobbering it.

    Returns a process exit code: 0 written, 2 refused, 1 error.
    """
    target = os.path.abspath(target)
    basename = os.path.basename(target)
    is_protected = basename in PROTECTED_TARGETS

    if os.path.exists(target):
        existing = sha256_of(target)
        existing_size = os.path.getsize(target)
        print(f"REFUSING: {target} already exists")
        print(f"  size   : {existing_size}")
        print(f"  sha256 : {existing}")
        if is_protected and not allow_overwrite:
            print("  This is a PROTECTED Phase 9 script.")
            print("  Re-run with --allow-overwrite ONLY if you intend to")
            print("  replace a verified script with generated content.")
            return 2
        if not allow_overwrite:
            print("  Pass --allow-overwrite to replace it deliberately.")
            return 2

    directory = os.path.dirname(target) or "."
    fd, tmp_path = tempfile.mkstemp(dir=directory, prefix=".gen-", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(content)
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(tmp_path, target)
    except Exception:
        if os.path.exists(tmp_path):
            os.unlink(tmp_path)
        raise
    print(f"written: {target} ({os.path.getsize(target)} bytes)")
    return 0


def _selftest() -> int:
    import hashlib as _h

    print("guard_helpers selftest")
    print(f"  helper sha256       : {sha256_of(os.path.abspath(__file__))}")
    print(f"  protected targets   : {', '.join(PROTECTED_TARGETS)}")
    # Verify a refusal decision without touching any real file.
    sample = "PROTECTED_TARGETS contains pg-backup-phase9.ps1: " + str(
        "pg-backup-phase9.ps1" in PROTECTED_TARGETS
    )
    print("  " + sample)
    digest = _h.sha256(b"ubos").hexdigest().upper()
    digest_ok = len(digest) == 64 and all(c in "0123456789ABCDEF" for c in digest)
    print(f"  hashlib usable      : {digest_ok} ({digest[:12]}...)")
    print("  selftest PASS (no files written)")
    return 0


if __name__ == "__main__":
    if "--selftest" in sys.argv:
        raise SystemExit(_selftest())
    print(__doc__)
    raise SystemExit(0)
